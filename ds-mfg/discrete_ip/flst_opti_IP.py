"""
This model describes a configuration selection optimization problem (discrete) for a 
flowsheet optimization of a drug substance manufacturing process described in [1]. 
The optimized configuration can then be implemented in a flowsheet simulator to be 
further optimized on the operational level. The manufacturing process consists of 5 
unit operations: reaction 1, reaction 2, vaporization, crystallization, and filtration. 
The model considers alternative unit selections for some unit operations: three choices 
for each reaction (PFR, CSTR, batch) and four choices for crystallization (1, 2, 3 
continuous MSMPR in series, batch). The model incorporates logical constraints such as 
the selection of a single unit for each operation, the selection of a hold tank if a 
batch process is selected following a continuous process, and flow conservation at each 
disjunction. The objective function for discrete optimization is to minimize capital cost. 
The model is formulated as an IP problem with disjunctive constraints and solved using Gurobi.

Additionally, an iterative process of adding an integer cut is implemented to find all 
feasible solutions to the problem. The integer cut is generated by adding a constraint 
that eliminates the current solution from the feasible region. The model is solved 
iteratively until no more feasible solutions are found.

References:
    [1] Daniel Casas-Orozco, Daniel J. Laky, Vivian Wang, Mesfin Abdi, Xin Feng, 
        Erin Wood, Gintaras V. Reklaitis, and Zoltan K. Nagy. Techno-economic analysis 
        of dynamic, end-to-end optimal pharmaceutical campaign manufacturing using pharmapy. 
        AIChE Journal, 69, 9, 2023. ISSN 15475905. doi: 10.1002/aic.18142.
    [2] Daniel J. Laky, Daniel Casas-Orozco, Carl D. Laird, Gintaras V. Reklaitis, 
        and Zoltan K. Nagy. Simulation-optimization framework for the digital design 
        of pharmaceutical processes using pyomo and pharmapy. Industrial and Engineering 
        Chemistry Research, 61: 16128–16140, 11 2022. ISSN 15205045. 
        https://pubs.acs.org/doi/abs/10.1021/acs.iecr.2c01636.
    [3] Barhate Y, Laky DJ, Casas-Orozco D, Reklaitis GV, Nagy ZK. Hybrid rule-based and 
        optimization-driven framework for the synthesis of end-to-end optimal pharmaceutical processes. 
        AIChE J. 2025;e18888. doi:10.1002/aic.18888.
"""

